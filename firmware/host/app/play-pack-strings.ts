export const PLAY_PACK_STRINGS: Readonly<Record<'ja' | 'en', Readonly<Record<string, string>>>> = Object.freeze({
  ja: Object.freeze(JA),
  en: Object.freeze(EN),
})

/** Resolves a message for a locale, falling back to Japanese, then to the key so gaps stay visible. */
export function formatPlayText(locale: string, key: string, values?: PlayTextValues): string {
  const table = locale === 'en' ? PLAY_PACK_STRINGS.en : PLAY_PACK_STRINGS.ja
  const template = table[key] ?? PLAY_PACK_STRINGS.ja[key] ?? key
  if (!values) return template
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  )
}
